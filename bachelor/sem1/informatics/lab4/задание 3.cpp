// Задача 2. Проверка, упорядочен ли массив по возрастанию (задача с флажком)
#include <iostream>
using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian");

    const int N = 5;
    int A[N] = { 5, 6, 9, 8, 10 };
    // int A[N] = {5, 6, 8, 9, 10}; // упорядоченный массив, для второй проверки

    // выводим массив на экран
    cout << "Массив: ";
    for (int i = 0; i < N; i++)
        cout << A[i] << " ";
    cout << endl;

    bool F = false; // флажок, пока нарушений нет он false
    int i = 0; // индекс левого элемента в паре соседей

    // идем по парам A[i] и A[i+1], пока не дошли до конца массива и пока F == false
    while (i < N - 1 && F == false)
    {
        if (A[i] >= A[i + 1]) // нарушение, левый не меньше правого
            F = true; // поднимаем флажок, дальше проверять нет смысла
        else
            i++; // A[i] < A[i+1], берем следующую пару
    }

    // результат смотрим по флажку
    if (F == false)
        cout << "Массив упорядочен по возрастанию" << endl;
    else
        cout << "Массив не упорядочен по возрастанию" << endl;

    return 0;
}